def digest_rows(conn, page_sql):
    # Trace SQL is generated by SQLite, from controlled benchmark parameters.
    sql, replacements = re.subn(r'LIMIT \d+ OFFSET \d+', 'LIMIT -1 OFFSET 0', page_sql, count=1)
    assert replacements == 1
    digest, count = hashlib.sha256(), 0
    for row in conn.execute(sql):
        digest.update(json.dumps(row, ensure_ascii=False, separators=(',', ':')).encode())
        digest.update(b'\n')
        count += 1
    return count, digest.hexdigest()


def run(path, old_source, rounds, selected_endpoints, selected_scenarios=None):
    mods = {'before': load('fuzzy_before', old_source), 'after': load('fuzzy_after')}
    conn = readonly(path)
    session = SimpleNamespace(connection=lambda: SimpleNamespace(connection=conn))
    results = []
    for endpoint in selected_endpoints:
        cases = scenarios()
        if selected_scenarios:
            cases = {k: v for k, v in cases.items() if k in selected_scenarios}
        if endpoint == 'standard_words':
            cases = {k: v for k, v in cases.items() if k in {
                'default-fuzzy', 'q-location-large', 'q-location-small', 'q-location-empty',
                'q-location-multi', 'one-character-location', 'definition-location',
                'detail-location', 'combined', 'q-wildcard', 'location-wildcard', 'q-broad-location', 'growth-high-hit'}}
        elif endpoint == 'map_points':
            cases = {k: v for k, v in cases.items() if k in {
                'default-fuzzy', 'q-location-large', 'q-location-small', 'combined'}}
        for name, params in cases.items():
            params = dict(params)
            if endpoint == 'standard_words':
                params['limit'] = None
            expected, plans, complete = None, {}, {}
            for version, module in mods.items():
                statements = []
                conn.set_trace_callback(statements.append)
                result = getattr(module, 'query_vocabulary_' + endpoint)(session=session, **params)
                conn.set_trace_callback(None)
                value = asdict(result)
                if expected is None:
                    expected = value
                assert expected == value, (endpoint, name, version)
                sqls = [s for s in statements if s.startswith('SELECT')]
                plans[version] = [dict(sql=s, plan=conn.execute('EXPLAIN QUERY PLAN ' + s).fetchall()) for s in sqls]
                if endpoint == 'items':
                    pages = [s for s in sqls if not s.startswith('SELECT COUNT(*)')]
                    complete[version] = digest_rows(conn, pages[-1]) if pages else (0, '')
                    assert complete[version][0] == result.total
                elif endpoint == 'standard_words':
                    assert len(result.standard_words) == result.total
            if endpoint == 'items':
                assert complete['before'] == complete['after'], (name, 'all matching rows')
            modes = ['cold-count', 'simulated-count-hit'] if endpoint == 'items' and name in {
                'default-fuzzy', 'q-location-large', 'q-location-small', 'q-location-empty'} else ['cold-count']
            for mode in modes:
                cache, samples, count_samples = {}, {v: [] for v in mods}, {v: [] for v in mods}
                for iteration in range(rounds + 1):
                    for version in (list(mods) if iteration % 2 == 0 else list(mods)[::-1]):
                        count_ms = 0.0
                        def count(sql, values):
                            nonlocal count_ms
                            key = (sql, tuple(values))
                            start = time.perf_counter()
                            if mode == 'simulated-count-hit' and key in cache:
                                value = cache[key]
                            else:
                                value = conn.execute(sql, values).fetchone()[0]
                                if mode == 'simulated-count-hit':
                                    cache[key] = value
                            count_ms += (time.perf_counter() - start) * 1000
                            return value
                        options = dict(params)
                        if endpoint == 'items':
                            options['_count_loader'] = count
                        start = time.perf_counter()
                        result = getattr(mods[version], 'query_vocabulary_' + endpoint)(session=session, **options)
                        elapsed = (time.perf_counter() - start) * 1000
                        assert asdict(result) == expected
                        if iteration:
                            samples[version].append(elapsed)
                            count_samples[version].append(count_ms)
                medians = {v: statistics.median(t) for v, t in samples.items()}
                row = dict(endpoint=endpoint, scenario=name, params=params, mode=mode,
                           total=getattr(result, 'total', getattr(result, 'total_entries', None)),
                           median_ms=medians, samples_ms=samples,
                           count_samples_ms=count_samples, plans=plans,
                           complete_entries_digest=complete,
                           reduction_percent=(1 - medians['after'] / medians['before']) * 100)
                results.append(row)
                print(endpoint, name, mode, {k: round(v, 3) for k, v in medians.items()}, flush=True)
    stats = dict(entries=conn.execute('SELECT COUNT(*) FROM vocabulary_entries').fetchone()[0],
                 word_spellings=conn.execute('SELECT COUNT(DISTINCT standard_word) FROM vocabulary_entries').fetchone()[0],
                 location_names=conn.execute('SELECT COUNT(DISTINCT location_name) FROM vocabulary_entries').fetchone()[0])
    conn.close()
    return dict(stats=stats, results=results)


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--baseline', default='HEAD')
    p.add_argument('--scale', type=int, default=1)
    p.add_argument('--distinct', action='store_true')
    p.add_argument('--rounds', type=int, default=7)
    p.add_argument('--endpoints', nargs='+', choices=['items', 'standard_words', 'map_points'],
                   default=['items', 'standard_words', 'map_points'])
    p.add_argument('--scenarios', nargs='+', choices=list(scenarios()))
    p.add_argument('--output', type=Path, required=True)
    args = p.parse_args()
    if args.scale < 1 or args.rounds < 3 or (args.distinct and args.scale < 2):
        p.error('scale >= 1, rounds >= 3; distinct growth needs scale >= 2')
    old = subprocess.check_output(['git', 'show', f'{args.baseline}:app/service/vocabulary/query.py'], cwd=ROOT, text=True)
    source = ROOT / 'data/vocabulary.db'
    report = dict(baseline=args.baseline, baseline_sha256=hashlib.sha256(old.encode()).hexdigest(),
                  current_sha256=hashlib.sha256((ROOT / 'app/service/vocabulary/query.py').read_bytes()).hexdigest(),
                  python=sys.version, sqlite=sqlite3.sqlite_version, platform=platform.platform(),
                  scale=args.scale, distinct=args.distinct, rounds=args.rounds,
                  note='Warm pages; sequential service calls; no real Redis/HTTP. All matching entry rows checked with bounded digest; standard words unlimited.')
    if args.scale == 1:
        report.update(run(source, old, args.rounds, args.endpoints, args.scenarios))
    else:
        with tempfile.TemporaryDirectory(prefix='vocabulary-fuzzy-validation-') as directory:
            target = Path(directory) / 'growth.db'
            growth_fixture(source, target, args.scale)
            if args.distinct:
                with readonly(source) as original:
                    stride = original.execute('SELECT MAX(user_id)+1 FROM ('
                        'SELECT user_id FROM vocabulary_entries UNION ALL SELECT user_id FROM vocabulary_locations)').fetchone()[0]
                with sqlite3.connect(target) as fixture:
                    for table in ['vocabulary_entries', 'vocabulary_locations']:
                        fixture.execute(f"UPDATE {table} SET location_name=location_name||'·新增'||user_id WHERE user_id>=?", (stride,))
                    fixture.execute("UPDATE vocabulary_entries SET standard_word=standard_word||'·新增'||user_id WHERE user_id>=?", (stride,))
            report.update(run(target, old, args.rounds, args.endpoints, args.scenarios))
    args.output.write_text(json.dumps(report, ensure_ascii=False, indent=2) + '\n')


if __name__ == '__main__':
    main()
